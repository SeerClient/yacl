"""Packs this mod into build/yet_another_config_lib_v3-<version>.seerm (SeerClient's mod package,
MODDING.md "Packaging: the .seerm file"). Generated by fabric2seer.

Prefer the SDK's own `seer pack` (tools/seer) - it builds, runs `seer check`
on every hook target and writes the same package. This script is the
no-dependency fallback:

    py pack.py
"""
import hashlib
import json
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
RUNTIME = "native"
PAYLOAD = "yacl.dll"
SKIP_DIRS = {"original", "todo", "src", "target", ".cargo", "build", ".seer", ".vscode"}
SKIP_FILES = {"pack.py", "PORTING_REPORT.md", "Cargo.toml", "Cargo.lock", ".gitignore"}


def built_payload():
    if RUNTIME == "native":
        cands = [os.path.join(HERE, "target", "release", PAYLOAD)]
    elif RUNTIME == "wasm":
        cands = [os.path.join(HERE, "target", "wasm32-unknown-unknown", "release", PAYLOAD)]
    else:
        return None
    for c in cands:
        if os.path.isfile(c):
            return c
    sys.exit(f"build the mod first: {cands[0]} is missing")


def main():
    with open(os.path.join(HERE, "seer.mod.json"), encoding="utf-8") as f:
        version = json.load(f).get("version", "0")
    os.makedirs(os.path.join(HERE, "build"), exist_ok=True)
    out = os.path.join(HERE, "build", f"yet_another_config_lib_v3-{version}.seerm")
    payload = built_payload()
    entries = {}
    for dp, dns, fns in os.walk(HERE):
        rel_dir = os.path.relpath(dp, HERE)
        top = rel_dir.split(os.sep)[0]
        if top in SKIP_DIRS:
            dns[:] = []
            continue
        dns[:] = [d for d in dns if not (rel_dir == "." and d in SKIP_DIRS)]
        for fn in fns:
            if rel_dir == "." and fn in SKIP_FILES:
                continue
            full = os.path.join(dp, fn)
            entries[os.path.relpath(full, HERE).replace(os.sep, "/")] = full
    if payload:
        entries[PAYLOAD] = payload
    lines = []
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(entries):
            with open(entries[name], "rb") as f:
                data = f.read()
            z.writestr(name, data)
            lines.append(f"{hashlib.sha256(data).hexdigest()}  {name}")
        # the integrity manifest `seer pack` writes too (sha256sum format, sorted by path)
        z.writestr("META-INF/seer.sha256", "\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
