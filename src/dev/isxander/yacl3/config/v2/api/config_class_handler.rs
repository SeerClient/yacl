/// java: public interface ConfigClassHandler<T>
///
/// A handled config class. `T` is the user's config class; its objects are Java references to mutable objects,
/// `compat::Shared<T>` (`HANDLER.instance()` is the live object: `compat::write(&HANDLER.instance(), |c| c.x = 1)`).
/// A Java `ConfigClassHandler<?>` is `Arc<dyn ConfigClassHandler<compat::Object>>`. Every method takes `&self`
/// (the handler is re-entered by its serializer while it loads).
pub trait ConfigClassHandler<T: 'static> {
    fn as_any(&self) -> &dyn std::any::Any;

    /// java: T instance(); - the working instance (get and set fields like usual)
    fn instance(&self) -> compat::Shared<T>;

    /// java: T defaults(); - a second instance for default values only; never modify it
    fn defaults(&self) -> compat::Shared<T>;

    /// java: Class<T> configClass();
    fn config_class(&self) -> compat::ClassOf<T>;

    /// java: ConfigField<?>[] fields();
    fn fields(&self) -> Vec<Arc<dyn ConfigField<compat::Object>>>;

    /// java: Identifier id(); - Java answers `null` for a handler built without an id: `id()` panics there
    /// (the `NullPointerException` of its first use)
    fn id(&self) -> Identifier;

    /// java: YetAnotherConfigLib generateGui();
    fn generate_gui(&self) -> Arc<dyn YetAnotherConfigLib>;

    /// java: boolean supportsAutoGen();
    fn supports_auto_gen(&self) -> bool;

    /// java: boolean load();
    fn load(&self) -> bool;

    /// java: void save();
    fn save(&self);

    /// java: @Deprecated ConfigSerializer<T> serializer();
    fn serializer(&self) -> Arc<dyn ConfigSerializer<T>>;
}

/// java: static <T> Builder<T> createBuilder(Class<T> configClass)
///
/// `T: ReflectedClass` is what Java's reflection over `configClass` needs (generated by fabric2seer).
pub fn create_builder<T: ReflectedClass>(config_class: &compat::ClassOf<T>) -> Arc<dyn Builder<T>> {
    BuilderImpl::<T>::new(*config_class)
}

/// java: interface Builder<T>
///
/// `&self` methods (state in cells), so a chain `create_builder(..).id(..).serializer(..).build()` reaches the same
/// object again while the previous call's receiver is still borrowed.
pub trait Builder<T: 'static> {
    fn as_any(&self) -> &dyn std::any::Any;

    /// java: Builder<T> id(Identifier id);
    fn id(&self, id: Identifier) -> Arc<dyn Builder<T>>;

    /// java: Builder<T> serializer(Function<ConfigClassHandler<T>, ConfigSerializer<T>> serializerFactory);
    fn serializer(
        &self,
        serializer_factory: Arc<dyn Fn(Arc<dyn ConfigClassHandler<T>>) -> Arc<dyn ConfigSerializer<T>>>,
    ) -> Arc<dyn Builder<T>>;

    /// java: ConfigClassHandler<T> build();
    fn build(&self) -> Arc<dyn ConfigClassHandler<T>>;
}
